#!/usr/bin/env node
"use strict";

// Fail the build if murk's release version disagrees anywhere it is declared.
//
// The original guard (ci.yaml) only compared Cargo.toml against
// node/package.json — which is exactly how node/package-lock.json silently
// drifted to 0.6.2 across v0.7.0 and v0.8.0: nothing cross-checked it. This
// checks every release-bumped location. Rust manifest versions come from
// `cargo metadata` (so a workspace member that drops `version.workspace = true`
// is caught), and the Cargo.lock entries are parsed directly so a stale lock is
// caught here too, before the expensive release build.
//
// Two further guards run after the main table: node/index.js is generated by
// napi-rs and embeds the package version in every native-binding
// version-check block, so a release that regenerates package.json but not
// index.js (e.g. a manual edit, or a `napi build` skipped in a hurry) would
// otherwise ship a binding that never enforces the real version. And
// integrations/bb/package.json pins @interrupted/murk-secrets by a semver
// range rather than an exact version, so it can silently stop covering the
// workspace version if a bump jumps past the range instead of into it.

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const read = (f) => fs.readFileSync(path.join(root, f), "utf8");

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--no-deps", "--format-version", "1"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 1 << 24,
  }),
);
const manifestVersion = (name) => {
  const p = meta.packages.find((x) => x.name === name);
  return p && p.version;
};

const lockVersion = (file, name) => {
  const m = read(file).match(new RegExp(`name = "${name}"\\nversion = "([^"]+)"`));
  return m && m[1];
};

// Every native-binding require() block in the generated index.js carries two
// copies of the version it enforces: the `!== '<ver>'` comparison and the
// `expected <ver> but got` half of the thrown message. Collect all of them —
// if they disagree with each other, the file was hand-edited or partially
// regenerated, which is its own bug distinct from a plain version bump.
const indexJsVersions = (() => {
  const src = read("node/index.js");
  const versions = new Set([
    ...[...src.matchAll(/bindingPackageVersion !== '([^']+)'/g)].map((m) => m[1]),
    ...[...src.matchAll(/mismatch, expected (\S+) but got/g)].map((m) => m[1]),
  ]);
  if (versions.size === 0) {
    console.error("::error::node/index.js has no napi binding version-check strings — was it regenerated correctly?");
    process.exit(1);
  }
  if (versions.size > 1) {
    console.error(
      `::error::node/index.js embeds disagreeing napi version-check strings: ${[...versions].join(", ")}`,
    );
    process.exit(1);
  }
  return [...versions][0];
})();

const pkg = JSON.parse(read("node/package.json"));
const lock = JSON.parse(read("node/package-lock.json"));

const locations = {
  "manifest: murk-cli": manifestVersion("murk-cli"),
  "manifest: murk-napi": manifestVersion("murk-napi"),
  "Cargo.lock: murk-cli": lockVersion("Cargo.lock", "murk-cli"),
  "Cargo.lock: murk-napi": lockVersion("Cargo.lock", "murk-napi"),
  // The fuzz crate is its own workspace with its own lockfile, and it depends
  // on murk-cli by path — so a release bump leaves it stale unless something
  // regenerates it. Nothing in CI passes --locked there, which is why this
  // drifted silently from v0.10.2 to v0.10.3; catch it here instead.
  "fuzz/Cargo.lock: murk-cli": lockVersion("fuzz/Cargo.lock", "murk-cli"),
  "node/package.json": pkg.version,
  "node/package-lock.json (root)": lock.version,
  "node/package-lock.json (packages[''])": lock.packages?.[""]?.version,
  "node/index.js (napi version check)": indexJsVersions,
};

for (const [where, version] of Object.entries(locations)) {
  console.log(`  ${String(version).padEnd(8)} ${where}`);
}

const distinct = [...new Set(Object.values(locations))];
if (distinct.length !== 1 || !distinct[0]) {
  console.error(
    `::error::murk version drift across ${Object.keys(locations).length} locations: ${distinct.join(", ")}`,
  );
  process.exit(1);
}
console.log(`OK: all versions consistent at ${distinct[0]}`);

// Minimal semver range satisfaction — enough for the caret/tilde/comparator
// ranges and "||" alternation actually used in this repo's manifests.
// Pulling in the `semver` package for one check felt heavier than this
// script's existing zero-dependency design.
const parseVersion = (v) => {
  const m = /^(\d+)\.(\d+)\.(\d+)/.exec(v);
  if (!m) throw new Error(`cannot parse semver version "${v}"`);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
};

const compareVersions = (a, b) => a[0] - b[0] || a[1] - b[1] || a[2] - b[2];

const satisfiesComparator = (comparator, version) => {
  const v = parseVersion(version);
  const caret = /^\^(\d+)\.(\d+)\.(\d+)/.exec(comparator);
  if (caret) {
    const base = [Number(caret[1]), Number(caret[2]), Number(caret[3])];
    if (compareVersions(v, base) < 0) return false;
    // Caret freezes the leftmost non-zero component; anything left of the
    // next component may vary, so the ceiling bumps just past it.
    const pivot = base[0] !== 0 ? 0 : base[1] !== 0 ? 1 : 2;
    const ceiling = base.slice();
    ceiling[pivot] += 1;
    for (let i = pivot + 1; i < 3; i++) ceiling[i] = 0;
    return compareVersions(v, ceiling) < 0;
  }
  const tilde = /^~(\d+)\.(\d+)\.(\d+)/.exec(comparator);
  if (tilde) {
    const base = [Number(tilde[1]), Number(tilde[2]), Number(tilde[3])];
    if (compareVersions(v, base) < 0) return false;
    return compareVersions(v, [base[0], base[1] + 1, 0]) < 0;
  }
  const cmp = /^(>=|<=|>|<|=)?(\d+)\.(\d+)\.(\d+)/.exec(comparator);
  if (cmp) {
    const base = [Number(cmp[2]), Number(cmp[3]), Number(cmp[4])];
    const c = compareVersions(v, base);
    switch (cmp[1] || "=") {
      case ">=":
        return c >= 0;
      case "<=":
        return c <= 0;
      case ">":
        return c > 0;
      case "<":
        return c < 0;
      default:
        return c === 0;
    }
  }
  throw new Error(`unsupported semver comparator "${comparator}"`);
};

const satisfiesRange = (range, version) =>
  range
    .split("||")
    .map((clause) => clause.trim())
    .some((clause) => clause.split(/\s+/).every((comparator) => satisfiesComparator(comparator, version)));

const bbPkg = JSON.parse(read("integrations/bb/package.json"));
const bbRange = bbPkg.dependencies?.["@interrupted/murk-secrets"];
if (!bbRange) {
  console.error("::error::integrations/bb/package.json no longer depends on @interrupted/murk-secrets");
  process.exit(1);
}
if (!satisfiesRange(bbRange, pkg.version)) {
  console.error(
    `::error::integrations/bb/package.json pins @interrupted/murk-secrets at "${bbRange}", which does not cover node/package.json's version ${pkg.version} — bump the range too`,
  );
  process.exit(1);
}
console.log(`OK: integrations/bb/package.json's "${bbRange}" range covers ${pkg.version}`);

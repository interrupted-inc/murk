"use strict";

// Keep an SPDX copyright and license header at the top of every source file
// the project authors.
//
//   node scripts/spdx-headers.cjs           add or update missing headers
//   node scripts/spdx-headers.cjs --check   list files without the header and
//                                           exit non-zero (CI runs this)
//
// The header is two SPDX tag lines (the REUSE convention) in the file's own
// comment syntax. The file set is every tracked file whose path matches a rule
// in STYLES below and no entry in SKIP. A new kind of source file needs a STYLES
// rule; a new generated or fixture path needs a SKIP entry with its reason.

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

// The single source of the copyright holder. Changing it here and running the
// script without --check rewrites the line in every file.
const COPYRIGHT_HOLDER = "murk contributors";
const LICENSE = "MIT OR Apache-2.0";

const TAGS = [
  `SPDX-FileCopyrightText: ${COPYRIGHT_HOLDER}`,
  `SPDX-License-Identifier: ${LICENSE}`,
];

const line = { slash: (t) => `// ${t}`, hash: (t) => `# ${t}`, block: (t) => `/* ${t} */` };

// First matching rule wins.
const STYLES = [
  [/\.(rs|ts|js|mjs|cjs)$/, line.slash],
  [/\.astro$/, line.slash], // inside the component-script fence
  [/\.css$/, line.block],
  [/\.(sh|bash|py|pyi|tape|rb\.template)$/, line.hash],
  [/(^|\/)(Makefile|Dockerfile)$/, line.hash],
  [/^\.githooks\/[^/]+$/, line.hash],
];

const SKIP = [
  // Generated by `cargo run --features doc-gen --bin gen-docs`.
  /^docs\/(completions|man)\//,
  // Generated by NAPI-RS on every binding build.
  /^node\/index\.(js|d\.ts)$/,
];

const root = path.resolve(__dirname, "..");

function trackedSources() {
  const out = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" });
  return out
    .split("\0")
    .filter(Boolean)
    .filter((f) => !SKIP.some((re) => re.test(f)))
    .map((f) => ({ file: f, style: STYLES.find(([re]) => re.test(f))?.[1] }))
    .filter(({ style }) => style);
}

// Lines that must stay above the header: a shebang (not a Rust `#![attr]`), or
// an Astro fence opener.
function preambleLength(file, lines) {
  if (/^#!(?!\[)/.test(lines[0] ?? "")) return 1;
  if (file.endsWith(".astro") && lines[0] === "---") return 1;
  return 0;
}

const HEAD_WINDOW = 8;
const tagLine = (tag) => new RegExp(`^\\W*${tag}:`);

// Returns the corrected text, or null if the file already has the header.
function withHeader(file, style, text) {
  const lines = text.split("\n");
  const want = TAGS.map(style);
  const head = lines.slice(0, HEAD_WINDOW);
  if (want.every((w) => head.includes(w))) return null;

  // Existing tags (e.g. an old copyright holder) are rewritten in place.
  const found = TAGS.map((t) => head.findIndex((l) => tagLine(t.split(":")[0]).test(l)));
  if (found.every((i) => i >= 0)) {
    found.forEach((i, n) => (lines[i] = want[n]));
    return lines.join("\n");
  }

  const at = preambleLength(file, lines);
  // A blank line separates the header from what follows.
  const sep = lines[at] === "" ? [] : [""];
  lines.splice(at, 0, ...want, ...sep);
  return lines.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const missing = [];
  for (const { file, style } of trackedSources()) {
    const abs = path.join(root, file);
    const fixed = withHeader(file, style, fs.readFileSync(abs, "utf8"));
    if (fixed === null) continue;
    missing.push(file);
    if (!check) fs.writeFileSync(abs, fixed);
  }

  if (check) {
    if (missing.length) {
      console.error(`${missing.length} source file(s) lack the SPDX header:`);
      for (const f of missing) console.error(`  ${f}`);
      console.error("Run `node scripts/spdx-headers.cjs` to add it.");
      process.exit(1);
    }
    console.log("All source files carry the SPDX header.");
  } else {
    console.log(`Updated ${missing.length} file(s).`);
  }
}

main();
